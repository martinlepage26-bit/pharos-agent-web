import fs from "node:fs/promises";
import path from "node:path";
import { assertCapability } from "../lib/policy";
import { recordAudit } from "../lib/audit";
import { DRAFTS_DIR, ensureDraftsDir, sha256, slugSegment } from "../lib/models";

export type CreateDraftInput = {
  projectKey: string;
  language: string;
  content: string;
  slugBase?: string;
};

export type CreateDraftOutput = {
  filePath: string;
  contentHash: string;
  bytes: number;
};

/**
 * Tool: create_local_brief_draft
 * The only write-capable tool in v1, and it writes to exactly one place:
 * the drafts/ directory inside this repository. Nothing is sent,
 * published, merged, or deleted.
 */
export async function createLocalBriefDraft(
  input: CreateDraftInput,
  runId?: string
): Promise<CreateDraftOutput> {
  // Build the real target BEFORE authorizing it. Checking the DRAFTS_DIR
  // constant instead of the file being written made the grant unfalsifiable.
  const date = new Date().toISOString().slice(0, 10);
  const slug = slugSegment(input.slugBase ?? "brief", "brief");
  // Case preserved so filenames stay "fr-CA", not "fr-ca"; stripping
  // separators and dots is what makes the segment safe, not lowercasing.
  const lang = slugSegment(input.language, "unspecified", { preserveCase: true });
  const fileName = `${date}-${slug}-${lang}.md`;
  const filePath = path.resolve(DRAFTS_DIR, fileName);

  // Defence in depth: slugSegment already strips separators and dots, so
  // this should be unreachable. It is the invariant the contract states,
  // so it is asserted rather than assumed.
  if (
    filePath !== DRAFTS_DIR &&
    !filePath.startsWith(DRAFTS_DIR + path.sep)
  ) {
    throw new Error(
      `refusing to write outside drafts/: ${filePath} is not under ${DRAFTS_DIR}`
    );
  }

  await assertCapability(
    "drafts.write",
    { path: filePath, projectKey: input.projectKey },
    runId
  );

  await ensureDraftsDir();

  const header =
    `<!-- DRAFT — human review required. Generated by pharos-agent. -->\n` +
    `<!-- project: ${input.projectKey} | language: ${input.language} -->\n\n`;

  const body = header + input.content;
  await fs.writeFile(filePath, body, "utf8");

  const hash = sha256(body);
  await recordAudit({
    runId,
    eventType: "draft_created",
    actor: "agent",
    toolName: "create_local_brief_draft",
    capability: "drafts.write",
    resourceRef: filePath,
    outcome: "success",
  });

  return { filePath, contentHash: hash, bytes: Buffer.byteLength(body) };
}
