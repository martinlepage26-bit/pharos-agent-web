import fs from "node:fs/promises";
import path from "node:path";
import { assertCapability } from "../lib/policy";
import { recordAudit } from "../lib/audit";
import { DRAFTS_DIR, ensureDraftsDir, sha256 } from "../lib/models";

export type CreateDraftInput = {
  projectKey: string;
  language: string;
  content: string;
  slugBase?: string;
};

export type CreateDraftOutput = {
  filePath: string;
  contentHash: string;
  bytes: number;
};

/**
 * Tool: create_local_brief_draft
 * The only write-capable tool in v1, and it writes to exactly one place:
 * the drafts/ directory inside this repository. Nothing is sent,
 * published, merged, or deleted.
 */
export async function createLocalBriefDraft(
  input: CreateDraftInput,
  runId?: string
): Promise<CreateDraftOutput> {
  await assertCapability(
    "drafts.write",
    { path: DRAFTS_DIR, projectKey: input.projectKey },
    runId
  );

  await ensureDraftsDir();
  const date = new Date().toISOString().slice(0, 10);
  const slug =
    (input.slugBase ?? "brief")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, "") || "brief";
  const fileName = `${date}-${slug}-${input.language}.md`;
  const filePath = path.join(DRAFTS_DIR, fileName);

  const header =
    `<!-- DRAFT — human review required. Generated by pharos-agent. -->\n` +
    `<!-- project: ${input.projectKey} | language: ${input.language} -->\n\n`;

  const body = header + input.content;
  await fs.writeFile(filePath, body, "utf8");

  const hash = sha256(body);
  await recordAudit({
    runId,
    eventType: "draft_created",
    actor: "agent",
    toolName: "create_local_brief_draft",
    capability: "drafts.write",
    resourceRef: filePath,
    outcome: "success",
  });

  return { filePath, contentHash: hash, bytes: Buffer.byteLength(body) };
}
